const nodes=new Map();
const attributes=new Map();
const attrs=['aria-label','placeholder','title'];
export function locale(){return localStorage.getItem('sw.language')==='en'?'en-GB':'it-IT';}
export function tr(value){return locale()==='en-GB'?english[value]||value:value;}
export function setLanguage(value){localStorage.setItem('sw.language',value==='en'?'en':'it');}
export function registerStatic(){
 const walker=document.createTreeWalker(document.body,NodeFilter.SHOW_TEXT);
 while(walker.nextNode()){
  const node=walker.currentNode,key=node.nodeValue.trim();
  if(Object.hasOwn(english,key))nodes.set(node,key);
 }
 for(const el of document.querySelectorAll('[aria-label],[placeholder],[title]')){
  const values=attrs.map(attr=>[attr,el.getAttribute(attr)]).filter(([,value])=>Object.hasOwn(english,value));
  if(values.length)attributes.set(el,values);
 }
}
const title=document.title;
export function translateStatic(){
 document.documentElement.lang=locale().slice(0,2);
 document.title=tr(title);
 for(const [node,key] of nodes)node.nodeValue=tr(key);
 for(const [node,values] of attributes)for(const [attr,key] of values)node.setAttribute(attr,tr(key));
}
